use ecolor::Color32;
use phf::phf_map;

#[macro_export]
macro_rules! hex_color {
	// We can't use ecolor::hex_color because that does not work in a static context.
	($s:literal) => {{
		let array = color_hex::color_from_hex!($s);
		ecolor::Color32::from_rgb(array[0], array[1], array[2])
	}};
}

#[inline]
#[must_use]
